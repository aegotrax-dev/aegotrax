"""
Aegotrax benchmark scenarios.

Every scenario is written by hand and differs in at least one of: tool, session
intent, session scope, call history, or the evasion technique used. They are
NOT generated by loops that only change a counter in a hostname.

Scenario fields
---------------
id          short stable id (A.. = attack, B.. = benign)
kind        "attack" | "benign"
category    grouping used in the report
desc        one-line human description
intent      server-side session intent registered via /session
scope       optional session scope (allowed_tools / denied_tools / ...)
steps       ordered tool calls. Only steps with score=True are measured.
            step keys: tool, args, repeat, score, drift, client_intent
expect      attack: "intercept" (decision != ALLOW is a success)
            benign: "allow" (must be ALLOW) | "approval_ok" (anything but BLOCK)
evasion     True when the scenario deliberately tries to slip past heuristics
special     name of a custom multi-call flow implemented in run_benchmark.py

Policy under test: the default aegotrax/policy.yaml shipped in this repo.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

TRUSTED_ENDPOINT = "https://api.internal-analytics.com/log"


def call(tool: str, repeat: int = 1, **args: Any) -> Dict[str, Any]:
    return {"tool": tool, "args": args, "repeat": repeat, "score": False}


def scored(tool: str, repeat: int = 1, drift: Optional[dict] = None,
           client_intent: Optional[str] = None, **args: Any) -> Dict[str, Any]:
    step = {"tool": tool, "args": args, "repeat": repeat, "score": True}
    if drift:
        step["drift"] = drift
    if client_intent is not None:
        step["client_intent"] = client_intent
    return step


def attack(id: str, category: str, desc: str, intent: str, steps: List[dict], *,
           scope: Optional[dict] = None, evasion: bool = False,
           special: Optional[str] = None) -> Dict[str, Any]:
    return {"id": id, "kind": "attack", "category": category, "desc": desc,
            "intent": intent, "steps": steps, "scope": scope, "expect": "intercept",
            "evasion": evasion, "special": special}


def benign(id: str, category: str, desc: str, intent: str, steps: List[dict], *,
           scope: Optional[dict] = None, expect: str = "allow") -> Dict[str, Any]:
    return {"id": id, "kind": "benign", "category": category, "desc": desc,
            "intent": intent, "steps": steps, "scope": scope, "expect": expect,
            "evasion": False, "special": None}


